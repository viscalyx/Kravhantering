import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { icons } from 'lucide-react'
import dynamicIconImports from 'lucide-react/dynamicIconImports.mjs'

export function generateStatusIconAliases(dynamicNames, canonicalNames) {
  const canonical = new Set(canonicalNames)
  const names = [
    ...new Set(
      dynamicNames.map(name =>
        name
          .split('-')
          .filter(Boolean)
          .map(part => part.charAt(0).toUpperCase() + part.slice(1))
          .join(''),
      ),
    ),
  ]
    .filter(name => !canonical.has(name))
    .sort((left, right) => left.localeCompare(right, 'en'))
  for (const name of names) {
    if (!/^[A-Za-z][A-Za-z0-9]*$/.test(name)) {
      throw new Error('Invalid status icon export name')
    }
  }
  return [
    '// Generated by scripts/generate-status-icon-aliases.mjs. Do not edit.',
    '// cspell:disable',
    'export {',
    ...names.map(name => `  ${name},`),
    "} from 'lucide-react'",
    '',
  ].join('\n')
}

/* v8 ignore start -- CLI orchestration writes the tested generated source. */
if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  writeFileSync(
    new URL('../lib/icons/status-icon-aliases.generated.ts', import.meta.url),
    generateStatusIconAliases(
      Object.keys(dynamicIconImports),
      Object.keys(icons),
    ),
  )
}
